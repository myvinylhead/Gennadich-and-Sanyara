// Уровень 5 — «Пицца-вселенная»: колесо пиццы, сырные мосты над томатным соусом, пепперони-пилы, печной жар.
// o  колесо (центр)   ~  сырный мост   p  пепперони-пила   V  печной жар
// n  ананас-еретик   d  оливки-дроны (3)   k  сырный слайм   r  курьер на мопеде
// Перепады — не больше 4 тайлов, провалы без помощи — не шире 6 (Геннадич без двойного прыжка).
(() => {
  const K = (w) => new GS.Chunk(w, 28).floor(24);
  // Провал с томатным соусом на дне.
  const pit = (c, x, w) => c.clear(x, 24, w, 4).fill(x, 26, w, 2, 'w');
  // Переправа на колесе: полка слева, колесо над соусом, полка справа наверху.
  const wheel = (c, x0) => {
    pit(c, x0 + 1, 21);
    c.put(x0 + 3, 21, '===').put(x0 + 11, 16, 'o').put(x0 + 16, 13, '========');
    c.put(x0 + 7, 14, 'C').put(x0 + 11, 10, 'C').put(x0 + 15, 14, 'C').put(x0 + 18, 12, 'C_C_C');
  };
  const chunks = [];

  // 1. Пицца-вселенная начинается: табличка, первые топпинги, коробки-ступеньки.
  {
    const c = K(40);
    c.fill(0, 0, 1, 24, '%');
    c.fill(22, 21, 3, 3, '%').fill(25, 19, 3, 5, '%');
    c.put(3, 23, '@').put(6, 23, 'T')
      .put(10, 21, 'C_C_C')
      .put(16, 23, 'n').put(23, 20, 'C').put(26, 18, 'C')
      .put(33, 23, 'k');
    chunks.push(c);
  }

  // 2. Колесо пиццы над соусом.
  {
    const c = K(44);
    c.put(5, 23, 'T');
    wheel(c, 10);
    c.put(39, 23, 'n');
    chunks.push(c);
  }

  // 3. Чекпоинт, сырные мосты над соусом: островки, пила, оливки-дроны и ананас на том берегу.
  {
    const c = K(44);
    pit(c, 8, 26);
    // Два коробки-островка — передохнуть; средний переход — два моста подряд без опоры.
    // Сверху пила (задевает в прыжке) и стая оливок, с того берега кидается ананас.
    c.fill(15, 21, 2, 7, '%').fill(31, 21, 2, 7, '%');
    c.put(3, 23, 'S')
      .put(9, 21, '~~~~~~').put(17, 21, '~~~~~~').put(25, 21, '~~~~~~')
      .put(20, 16, 'p')
      .put(24, 15, 'd')
      .put(38, 23, 'n')
      .put(11, 19, 'C').put(19, 19, 'C').put(27, 19, 'C').put(15, 18, 'K');
    chunks.push(c);
  }

  // 4. Башня из коробок: подняться можно только на печном жаре.
  {
    const c = K(46);
    c.fill(14, 12, 6, 12, '%');
    c.put(5, 23, 'T').put(11, 23, 'V')
      .put(11, 17, 'C').put(11, 13, 'C')
      .put(17, 11, 'n').put(15, 11, 'C')
      .put(21, 15, '====').put(26, 18, '====')
      .put(34, 23, 'r').put(30, 21, 'C_C_C_C').put(42, 23, 'k');
    chunks.push(c);
  }

  // 5. Чекпоинт, второе колесо, пилы на полу и тайник с кошкой над печным жаром.
  {
    const c = K(50);
    c.put(3, 23, 'S');
    wheel(c, 6);
    c.put(36, 22, 'p').put(41, 22, 'p')
      .put(46, 23, 'V').put(43, 10, '======').put(47, 9, '$').put(44, 9, 'C')
      .put(39, 15, 'd');
    chunks.push(c);
  }

  // 6. Последний рывок к порталу, за которым — главная пицца.
  {
    const c = K(40);
    c.fill(38, 0, 2, 24, '%');
    c.put(4, 22, 'P').put(8, 21, 'C_C_C_C_C')
      .put(12, 23, 'n').put(20, 23, 'k').put(24, 23, 'n')
      .put(18, 20, '====').put(19, 19, 'D')
      .put(32, 23, 'E');
    chunks.push(c);
  }

  GS.LEVEL_PIZZA = {
    id: 'pizza',
    name: 'ПИЦЦА-ВСЕЛЕННАЯ',
    subtitle: 'ЧЕТЫРЕ СЫРА И НИ ОДНОГО АНАНАСА',
    theme: 'pizza',
    music: 'pizza',
    signs: GS.LINES.signs.pizza,
    map: GS.joinChunks(chunks.map((c) => ({ w: c.w, rows: c.rows }))),
    parTime: 170,
    exitOpen: true,
    exitLabel: 'К ГЛАВНОЙ ПИЦЦЕ!',
  };
})();
