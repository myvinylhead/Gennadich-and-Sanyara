// Уровень 7 — «Церковь Святого Покока»: фанатики промптов, контекстные окна, скиллы-реликвии.
// F  фанатик   H  аколит AGENTS.MD   e  токенизатор   y  хор   i  инквизитор «grill-me»
// I  колонна «САММАРИ»   [ … ]  контекстное окно   Q  реликвия-скилл (по порядку: TDD, CAVEMAN, DIAGNOSE)
// Свечи — шипы «^». Перепады — не больше 4 тайлов (Геннадич без двойного прыжка).
(() => {
  const K = (w) => new GS.Chunk(w, 28).floor(24);
  const chunks = [];

  // 1. Вход в собор: скамьи, свечи, первый фанатик и инквизитор на балконе.
  {
    const c = K(40);
    c.fill(0, 0, 1, 24, '%');
    c.fill(12, 23, 4, 1, '%').fill(20, 23, 4, 1, '%');
    c.put(3, 23, '@').put(6, 23, 'T')
      .put(9, 21, 'C_C_C')
      .put(26, 23, '^^')
      .put(31, 23, 'F')
      .put(34, 20, '=====').put(36, 19, 'i').put(35, 18, 'C');
    chunks.push(c);
  }

  // 2. Первое контекстное окно: две колонны «САММАРИ», фанатик и аколит.
  {
    const c = K(50);
    c.put(2, 23, 'T')
      .put(5, 23, '[').put(44, 23, ']')
      .put(15, 23, 'I').put(32, 23, 'I')
      .put(22, 23, 'F').put(38, 23, 'H')
      .put(18, 20, '======').put(26, 17, '=====')
      .put(19, 19, 'C_C_C').put(27, 16, 'C_C');
    chunks.push(c);
  }

  // 3. Исповедальня, реликвия TDD, токенизатор, хор с охраной.
  {
    const c = K(44);
    c.fill(16, 23, 3, 1, '%');
    c.put(3, 23, 'S').put(8, 23, 'Q').put(11, 23, 'T')
      .put(20, 23, 'e')
      .put(22, 19, '=====').put(24, 18, 'i')
      .put(29, 23, 'H').put(34, 23, 'y').put(39, 23, 'F')
      .put(23, 17, 'C_C');
    chunks.push(c);
  }

  // 4. Подъём по балконам нефа: наверху реликвия CAVEMAN, в нише — золотая кошка.
  {
    const c = K(46);
    c.fill(36, 23, 3, 1, '%');
    c.put(3, 23, 'T')
      .put(8, 20, '=====').put(13, 16, '=====').put(8, 12, '=====').put(14, 8, '================')
      .put(9, 11, '$').put(11, 11, 'C')
      .put(17, 7, 'Q').put(22, 7, 'C_C_C').put(26, 7, 'F')
      .put(14, 15, 'F')
      .put(24, 23, 'H').put(33, 23, 'e').put(41, 23, 'F')
      .put(30, 12, '====').put(34, 16, '====').put(38, 20, '====');
    chunks.push(c);
  }

  // 5. Исповедальня, реликвия DIAGNOSE и большое окно: три колонны, хор подпевает врагам.
  {
    const c = K(52);
    c.put(3, 23, 'S').put(6, 23, 'Q')
      .put(10, 23, '[').put(48, 23, ']')
      .put(18, 23, 'I').put(29, 23, 'I').put(40, 23, 'I')
      .put(14, 23, 'e').put(24, 23, 'F').put(34, 23, 'H').put(44, 23, 'y')
      .put(21, 20, '=====').put(34, 20, '=====').put(22, 19, 'C_C').put(35, 19, 'C_C');
    chunks.push(c);
  }

  // 6. Алтарь и портал к Архиепископу.
  {
    const c = K(40);
    c.fill(38, 0, 2, 24, '%');
    c.put(5, 21, 'C_C_C_C')
      .put(12, 20, '=====').put(14, 19, 'i').put(13, 18, 'P')
      .put(22, 23, 'F').put(27, 23, 'H')
      .put(33, 23, 'E');
    chunks.push(c);
  }

  GS.LEVEL_CHURCH = {
    id: 'church',
    name: 'ЦЕРКОВЬ СВЯТОГО ПОКОКА',
    subtitle: 'ПРОМПТ НАШ НАСУЩНЫЙ',
    theme: 'church',
    music: 'church',
    signs: GS.LINES.signs.church,
    map: GS.joinChunks(chunks.map((c) => ({ w: c.w, rows: c.rows }))),
    parTime: 200,
    exitOpen: true,
    exitLabel: 'К АЛТАРЮ',
    startSticker: 'church',
    checkpointTex: ['church/booth0', 'church/booth1'],
    checkpointTitle: 'ИСПОВЕДЬ ПРИНЯТА',
    checkpointMsgs: GS.LINES.confessions,
  };
})();
