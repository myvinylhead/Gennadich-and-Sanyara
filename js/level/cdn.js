// Уровень 3 — «Гонка по CDN»: слева наступает стена-404, бежим через узлы доставки.
// >  ускоритель   J  батут (верхний маршрут)   m  платформа над каналом битых данных.
// Перепады по высоте — не больше 4 тайлов, провалы без ускорения — не шире 6: Геннадич без двойного прыжка.
(() => {
  const K = (w) => new GS.Chunk(w, 28).floor(24);
  // Провал с «битыми данными» на дне.
  const pit = (c, x, w) => c.clear(x, 24, w, 4).fill(x, 26, w, 2, 'w');
  const chunks = [];

  // 1. Старт: табличка, первый ускоритель и провал, который с разгона берётся играючи.
  {
    const c = K(44);
    c.fill(0, 0, 1, 24, '%');
    pit(c, 23, 6);
    c.put(3, 23, '@').put(6, 23, 'T')
      .put(10, 21, 'C_C_C')
      .put(16, 23, '>>')
      .put(23, 20, 'C_C_C')
      .put(34, 23, 'h').put(40, 23, 'b');
    chunks.push(c);
  }

  // 2. Развилка: батут наверх (рельс с ускорителем и монетами) или низом через провалы и хрючево.
  {
    const c = K(48);
    pit(c, 12, 4); pit(c, 24, 4);
    c.put(2, 23, 'T').put(5, 23, 'J')
      .put(6, 16, '=================================')
      .put(9, 15, 'C_C_C_C_C').put(20, 15, '>>').put(30, 15, 'D').put(33, 15, 'C_C')
      .put(19, 23, 'h').put(31, 23, 'b').put(36, 23, 'h')
      .put(26, 9, 'f');
    chunks.push(c);
  }

  // 3. Чекпоинт, кофе и длинный провал: с ускорителя — одним прыжком, без него — через полку.
  {
    const c = K(44);
    pit(c, 10, 5); pit(c, 22, 9);
    c.put(3, 23, 'S').put(7, 22, 'K')
      .put(17, 23, '>>')
      .put(25, 22, '===')
      .put(23, 19, 'C_C_C_C')
      .put(14, 14, 'f').put(34, 13, 'f')
      .put(38, 23, 'h');
    chunks.push(c);
  }

  // 4. Канал битых данных: катаемся на платформах, ждать некогда.
  {
    const c = K(46);
    pit(c, 6, 30);
    c.fill(19, 21, 4, 7, '#');
    c.put(12, 22, 'm').put(29, 22, 'm')
      .put(20, 20, 'C_C')
      .put(10, 18, 'C').put(14, 18, 'C').put(27, 18, 'C').put(31, 18, 'C')
      .put(41, 23, 'R');
    chunks.push(c);
  }

  // 5. Подъём по стойкам серверов; батут на вершине — к тайнику с кошкой.
  {
    const c = K(44);
    c.fill(10, 21, 6, 3, '#').fill(16, 18, 6, 6, '#').fill(22, 15, 8, 9, '#')
      .fill(30, 18, 5, 6, '#').fill(35, 21, 4, 3, '#');
    c.put(29, 6, '==========').put(36, 5, '$').put(31, 5, 'C_C')
      .put(28, 14, 'J')
      .put(12, 20, 'C').put(18, 17, 'C').put(24, 14, 'C')
      .put(20, 11, 'W').put(25, 14, 'g')
      .put(6, 23, 'b').put(41, 23, 'h');
    chunks.push(c);
  }

  // 6. Чекпоинт и вторая развилка: глитч-мост поверху или тоннель с шипами понизу.
  {
    const c = K(46);
    c.fill(12, 19, 24, 1, '%');
    c.put(3, 23, 'S').put(8, 23, 'J')
      // Глитч-блоки — там, где дуга батута идёт вниз: блок прямо над батутом бьёт по голове.
      .put(14, 16, 'GG').put(19, 15, 'GG').put(24, 16, 'GG').put(29, 15, 'GG')
      .put(33, 16, '=========')
      .put(15, 14, 'C').put(20, 13, 'C').put(25, 14, 'C').put(30, 13, 'C').put(37, 15, '>>')
      .put(16, 20, 'vvv').put(27, 20, 'vv')
      .put(20, 23, 'h').put(30, 23, 'b');
    chunks.push(c);
  }

  // 7. Финишная прямая: цепочка ускорителей, пицца и портал выхода.
  {
    const c = K(50);
    c.fill(48, 0, 2, 24, '%');
    c.put(4, 23, '>>').put(18, 23, '>>').put(32, 23, '>>')
      .put(10, 22, 'P')
      .put(7, 21, 'C_C_C_C_C_C').put(21, 21, 'C_C_C_C_C_C')
      .put(12, 23, 'b').put(24, 23, 'h').put(28, 23, 'b').put(22, 15, 'f')
      .put(44, 23, 'E');
    chunks.push(c);
  }

  GS.LEVEL_CDN = {
    id: 'cdn',
    name: 'ГОНКА ПО CDN',
    subtitle: 'ДОСТАВКА ЗА 404 МИЛЛИСЕКУНДЫ',
    theme: 'cdn',
    music: 'cdn',
    signs: GS.LINES.signs.cdn,
    map: GS.joinChunks(chunks.map((c) => ({ w: c.w, rows: c.rows }))),
    parTime: 70,
    exitOpen: true,
    moverSpeed: 70,
    // Стена-404: скорость по участкам (x в пикселях → px/с), догон из-за кадра, рестарт у чекпоинта.
    chase: {
      delay: 3, speed: [[0, 90], [1500, 100], [3000, 110], [4200, 118]],
      catchup: 240, catchupGap: 70, restartGap: 230, restartDelay: 2, damage: 2, spitAhead: 70,
    },
  };
})();
