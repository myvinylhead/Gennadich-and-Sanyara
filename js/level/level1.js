// Уровень 1 — «Посадочная страница»: обучение на нейропланете, артефакт, портал.
(() => {
  const K = (w) => new GS.Chunk(w, 28);
  const chunks = [];

  // 1. Старт: приветствие, дуга монет, полки.
  chunks.push(K(40).floor()
    .put(3, 22, '@').put(6, 22, 'T')
    .put(12, 20, 'C').put(14, 19, 'C').put(16, 20, 'C')
    .put(17, 19, '=====').put(18, 17, 'C_C')
    .put(26, 15, '=======').put(27, 13, 'C_C_C')
    .fill(29, 21, 4, 2, '%')
    .put(36, 22, 'T'));

  // 2. Первое хрючево, шипы, плато.
  chunks.push(K(40).floor()
    .put(8, 22, 'h')
    .clear(13, 23, 4, 1).put(13, 24, '^^^^')
    .put(16, 20, '===')
    .fill(20, 18, 10, 5, '#')
    .put(21, 16, 'C_C_C_C')
    .put(27, 17, 'h')
    .clear(32, 23, 3, 1).put(32, 24, '^^^')
    .put(33, 19, '====').put(34, 17, 'C')
    .put(38, 22, 'h'));

  // 3. Стрельба во все стороны: летучие, лестница из полок, островок с пиццей.
  chunks.push(K(40).floor()
    .put(2, 22, 'T')
    .put(10, 19, '====').put(11, 18, 'C')
    .put(16, 16, '====').put(17, 15, 'C')
    .put(22, 13, '=====').put(23, 12, 'C_C')
    .fill(28, 11, 10, 2, '#').put(33, 10, 'P').put(30, 10, 'C')
    .put(14, 13, 'f').put(30, 7, 'f')
    .put(20, 22, 'b').put(31, 22, 'b')
    .put(37, 22, 'h'));

  // 4. Чекпоинт, кофе, яма со слизью и платформа, руины с гранатомётчиком.
  chunks.push(K(40).floor()
    .put(4, 22, 'S').put(9, 22, 'K')
    .clear(14, 23, 12, 2).fill(14, 25, 12, 3, 'w')
    .put(15, 21, 'm')
    .put(24, 19, '==')
    .put(17, 18, 'C_C_C')
    .fill(26, 17, 8, 6, '%')
    .put(30, 16, 'g')
    .put(36, 22, 'b').put(38, 20, 'C'));

  // 5. Спецприём: наверху — секретная пещера с золотой кошкой и «Я ПОМОГ».
  chunks.push(K(40).floor()
    .put(2, 22, 'T')
    .put(3, 19, '===').put(6, 16, '===')
    .fill(8, 13, 5, 1, '#').put(9, 12, 'C_C')
    // Пещера: перелететь 7 тайлов можно только рывком или сеткой.
    .fill(20, 8, 12, 1, '#').fill(20, 13, 12, 1, '#').fill(31, 8, 1, 6, '#')
    .fill(21, 9, 10, 4, ':')
    .put(23, 12, 'Y').put(28, 12, '$').put(25, 10, 'C_C')
    .put(14, 22, 'b').put(22, 22, 'h').put(29, 22, 'b')
    .put(18, 19, 'C_C_C').put(34, 22, 'h'));

  // 6. Долина спящего хрючева: лучше прокрасться по полкам.
  chunks.push(K(40).floor()
    .put(3, 22, 'T').put(6, 19, 'D')
    .clear(9, 23, 21, 2)
    .put(19, 24, 'z')
    .put(11, 19, '=====').put(21, 19, '=====')
    .put(12, 17, 'C_C').put(22, 17, 'C_C')
    .put(33, 22, 'h').put(37, 22, 'h'));

  // 7. Чекпоинт и подъём к артефакту.
  chunks.push(K(40).floor()
    .put(3, 22, 'S').put(6, 22, 'T')
    .put(9, 19, '====').put(14, 15, '====').put(9, 11, '====').put(14, 7, '=====')
    .put(10, 18, 'C').put(15, 14, 'C').put(10, 10, 'C').put(16, 6, 'P')
    .fill(21, 6, 9, 1, '%').put(25, 5, 'A').put(22, 5, 'C').put(28, 5, 'C')
    .put(27, 11, 'f').put(33, 9, 'f')
    .fill(31, 17, 6, 6, '#').put(33, 16, 'g')
    .put(20, 22, 'h'));

  // 8. Финиш: портал.
  chunks.push(K(36).floor()
    .put(6, 22, 'h').put(12, 22, 'b').put(16, 20, 'C_C_C_C')
    .put(29, 22, 'E')
    .fill(34, 4, 2, 19, '#'));

  GS.LEVEL1 = {
    id: 'level1',
    name: 'ПОСАДОЧНАЯ СТРАНИЦА',
    subtitle: 'НЕЙРОПЛАНЕТА-1',
    theme: 'planet',
    music: 'level1',
    signs: GS.LINES.signs.level1,
    map: GS.joinChunks(chunks.map((c) => ({ w: c.w, rows: c.rows }))),
    parTime: 240,
  };
})();
