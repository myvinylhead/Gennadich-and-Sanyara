// Уровень 2 — «Попап-мегаполис»: крыши, глитч-мосты, окна-монстры, Петушня и Клод-мех.
(() => {
  const K = (w) => new GS.Chunk(w, 28);
  // Здание: крыша «#» и корпус из окон «%».
  const bld = (c, x, top, w, bottom = 28) => c.fill(x, top, w, 1, '#').fill(x, top + 1, w, bottom - top - 1, '%');
  const chunks = [];

  // 1. Старт на крыше, первые попапы.
  {
    const c = K(36);
    bld(c, 0, 20, 22); bld(c, 26, 18, 10);
    c.put(2, 19, '@').put(5, 19, 'T')
      .put(10, 18, 'C_C_C')
      .put(17, 14, 'W')
      .put(24, 16, 'C')
      .put(31, 17, 'h');
    chunks.push(c);
  }

  // 2. Мост из глитч-блоков над пропастью.
  {
    const c = K(40);
    bld(c, 0, 18, 6); bld(c, 28, 16, 12);
    c.put(2, 17, 'T')
      .put(8, 18, 'GG').put(13, 18, 'GG').put(18, 18, 'GG').put(23, 18, 'GG')
      .put(9, 16, 'C').put(14, 16, 'C').put(19, 16, 'C').put(24, 16, 'C')
      .put(13, 10, 'W').put(23, 8, 'W')
      .put(34, 15, 'R').put(30, 13, 'D');
    chunks.push(c);
  }

  // 3. Чекпоинт, спуск на улицу, гранатомётчик и тайная комната с кошкой в здании.
  {
    const c = K(40);
    bld(c, 0, 16, 10);
    c.fill(10, 24, 30, 4, '#');
    bld(c, 20, 17, 11, 24);
    c.put(27, 17, '==').fill(27, 18, 2, 1, ':');
    c.clear(21, 19, 8, 3).fill(21, 19, 8, 3, ':');
    c.put(23, 21, '$').put(26, 21, 'P').put(25, 19, 'C');
    c.put(3, 15, 'S')
      .put(12, 23, 'K')
      .put(15, 23, 'b').put(35, 23, 'b')
      .put(24, 16, 'g')
      .put(33, 23, 'h').put(37, 23, 'h')
      .put(11, 20, '===').put(15, 18, '===').put(14, 21, 'C_C');
    chunks.push(c);
  }

  // 4. Ящик Клод-меха и толпа.
  {
    const c = K(44);
    c.fill(0, 24, 44, 4, '#');
    bld(c, 20, 21, 6, 24);
    c.put(2, 23, 'T').put(7, 23, 'M')
      .put(13, 23, 'h').put(17, 23, 'h').put(28, 23, 'h').put(32, 23, 'h').put(36, 23, 'b').put(40, 23, 'h')
      .put(15, 15, 'f').put(30, 14, 'f')
      .put(22, 20, 'g')
      .put(38, 23, 'R')
      .put(10, 21, 'C_C_C_C_C_C_C_C_C_C_C_C_C_C_C');
    chunks.push(c);
  }

  // 5. Подъём по фасаду небоскрёба.
  {
    const c = K(40);
    c.fill(0, 24, 26, 4, '#');
    bld(c, 26, 6, 14);
    c.put(5, 23, 'S')
      .put(17, 20, '=====').put(21, 16, '=====').put(16, 12, '=====').put(21, 8, '=====')
      .put(18, 19, 'C').put(22, 15, 'C').put(17, 11, 'C').put(19, 11, 'D').put(22, 7, 'C')
      .put(12, 14, 'W').put(14, 6, 'f')
      .put(10, 23, 'b').put(14, 23, 'h')
      .put(32, 5, 'P').put(36, 5, 'h');
    chunks.push(c);
  }

  // 6. Крыши на высоте, снова глитчи, артефакт.
  {
    const c = K(40);
    bld(c, 0, 6, 12); bld(c, 27, 9, 13);
    c.put(5, 5, 'T')
      .put(14, 8, 'GG').put(18, 7, 'GG').put(22, 8, 'GG')
      .put(15, 6, 'C').put(19, 5, 'C').put(23, 6, 'C')
      .put(18, 2, 'W')
      .put(29, 8, 'R')
      .put(34, 8, 'A').put(33, 6, 'C_C_C');
    chunks.push(c);
  }

  // 7. Спуск к порталу.
  {
    const c = K(36);
    bld(c, 0, 9, 6); bld(c, 6, 13, 5); bld(c, 11, 17, 5); bld(c, 16, 21, 4);
    c.fill(20, 24, 16, 4, '#');
    c.put(8, 12, 'h').put(13, 16, 'b').put(22, 20, 'W')
      .put(29, 23, 'E')
      .fill(34, 2, 2, 22, '%');
    chunks.push(c);
  }

  GS.LEVEL2 = {
    id: 'level2',
    name: 'ПОПАП-МЕГАПОЛИС',
    subtitle: 'ПРИНЯТЬ ВСЕ COOKIES?',
    theme: 'city',
    music: 'level2',
    signs: GS.LINES.signs.level2,
    map: GS.joinChunks(chunks.map((c) => ({ w: c.w, rows: c.rows }))),
    parTime: 300,
  };
})();
