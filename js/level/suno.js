// Уровень 4 — «Студия SUNO»: ритм-платформер, всё живёт в такт треку. В конце — гитар-дуэль (RhythmScene).
// q  эквалайзер   U  сабвуфер   L  лазер-метроном   N  нота-монета
// x  фальшивая нота   a  автотюн-хрючево   c  копирайт-бот   u  мьют-призрак
// Перепады — не больше 4 тайлов, провалы без помощи — не шире 6 (Геннадич без двойного прыжка).
(() => {
  const K = (w) => new GS.Chunk(w, 28).floor(24);
  // Провал с «фальшивым звуком» на дне.
  const pit = (c, x, w) => c.clear(x, 24, w, 4).fill(x, 26, w, 2, 'w');
  const chunks = [];

  // 1. Вход в студию: табличка и первые эквалайзеры над провалом.
  {
    const c = K(40);
    c.fill(0, 0, 1, 24, '%');
    pit(c, 15, 9);
    c.put(3, 23, '@').put(6, 23, 'T')
      .put(9, 21, 'N_N_N')
      .put(16, 22, 'q').put(19, 21, 'q').put(22, 22, 'q')
      .put(17, 18, 'N').put(20, 17, 'N').put(23, 18, 'N')
      .put(30, 23, 'h').put(35, 16, 'x');
    chunks.push(c);
  }

  // 2. Сабвуфер на верхнюю полку или низом через лазеры-метрономы.
  {
    const c = K(44);
    c.put(3, 23, 'T').put(8, 23, 'U')
      .put(10, 16, '=============')
      .put(12, 15, 'N_N_N_N_N').put(20, 15, 'D')
      .put(14, 23, 'L').put(19, 23, 'L').put(24, 23, 'L')
      .put(16, 21, 'N').put(21, 21, 'N')
      .put(30, 17, 'c').put(36, 23, 'a');
    chunks.push(c);
  }

  // 3. Чекпоинт, автотюн-хрючево и лестница из эквалайзеров.
  {
    const c = K(46);
    c.fill(18, 21, 5, 3, '#').fill(23, 18, 5, 6, '#');
    c.put(3, 23, 'S')
      .put(12, 23, 'a')
      .put(29, 20, 'q').put(32, 17, 'q').put(35, 14, 'q')
      .put(37, 13, '======')
      .put(30, 17, 'N').put(33, 14, 'N').put(36, 11, 'N').put(39, 12, 'K')
      .put(20, 20, 'N').put(25, 17, 'N')
      .put(26, 10, 'x');
    chunks.push(c);
  }

  // 4. Поле эквалайзеров над провалом — и мьют-призрак, который их глушит.
  {
    const c = K(46);
    pit(c, 9, 26);
    for (let i = 0; i < 8; i++) c.put(10 + i * 3, i % 2 ? 21 : 22, 'q');
    c.put(11, 19, 'N').put(17, 18, 'N').put(23, 19, 'N').put(29, 18, 'N')
      .put(21, 14, 'u')
      .put(40, 18, 'c').put(5, 23, 'P');
    chunks.push(c);
  }

  // 5. Чекпоинт, полка с лазерами поверху, фальшивые ноты понизу.
  {
    const c = K(44);
    c.put(3, 23, 'S').put(6, 23, 'T').put(10, 23, 'U')
      .put(12, 16, '==============')
      .put(15, 15, 'L').put(21, 15, 'L')
      .put(13, 15, 'N').put(18, 15, 'N_N').put(24, 15, 'N')
      .put(16, 18, 'x').put(26, 19, 'x')
      .put(20, 23, 'a').put(32, 23, 'b').put(36, 23, 'h');
    chunks.push(c);
  }

  // 6. Сцена: последняя табличка и дверь на гитар-дуэль.
  {
    const c = K(40);
    c.fill(38, 0, 2, 24, '%');
    c.put(4, 23, 'T')
      .put(8, 21, 'N_N_N_N_N_N')
      .put(14, 22, 'q').put(18, 21, 'q')
      .put(24, 23, 'U').put(26, 16, '======').put(29, 15, '$')
      .put(33, 23, 'E');
    chunks.push(c);
  }

  GS.LEVEL_SUNO = {
    id: 'suno',
    name: 'СТУДИЯ SUNO',
    subtitle: 'ХРЮЧЕВО ГЕНЕРИТ ХИТЫ',
    theme: 'suno',
    music: 'suno',
    signs: GS.LINES.signs.suno,
    map: GS.joinChunks(chunks.map((c) => ({ w: c.w, rows: c.rows }))),
    parTime: 150,
    rhythm: true,
    duel: true,
    exitOpen: true,
    exitLabel: 'НА СЦЕНУ!',
  };
})();
