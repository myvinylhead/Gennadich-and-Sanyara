// Случайная реплика героя по событию.
GS.line = (event, hero) => {
  const set = GS.LINES.hero[event];
  if (!set) return '';
  const pool = [...(set.all || []), ...((hero && set[hero]) || []), ...((hero && set[hero]) || [])];
  return pool.length ? GS.util.pick(pool) : '';
};
